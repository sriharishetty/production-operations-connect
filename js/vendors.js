function applyAdminVendorOverrides() {

    let adminVendors;


    try {

        adminVendors = JSON.parse(
            localStorage.getItem(
                "productionOperationsVendors"
            )
        );

    } catch (error) {

        return;

    }


    if (!Array.isArray(adminVendors)) {
        return;
    }


    const vendorsBySourceRow =
        new Map(
            window.vendorData.map(
                function (vendor) {

                    return [vendor.sourceRow, vendor];

                }
            )
        );


    const fieldMap = {
        systemName: "systemName",
        category: "category",
        vendorCompanyName: "vendor",
        vendorPOC: "vendorPoc",
        contactNumbers: "phone",
        emailAddress: "email",
        aagItsPOC: "aagItsPoc",
        aagItsTeam: "aagItsTeam",
        prodOpsEscalationProcess: "escalation",
        infoUpdatedDate: "updatedDate",
        infoUpdatedBy: "updatedBy",
        infoApprovedDate: "approvedDate",
        infoApprovedBy: "approvedBy",
        /* Compatibility with previously saved Admin edits. */
        company: "vendor",
        poc: "vendorPoc",
        phone: "phone",
        email: "email",
        aagItsPoc: "aagItsPoc",
        escalation: "escalation",
        updatedDate: "updatedDate",
        updatedBy: "updatedBy",
        approvedDate: "approvedDate",
        approvedBy: "approvedBy"
    };


    adminVendors.forEach(
        function (adminVendor) {

            const sourceRow =
                adminVendor.sourceRow ||
                ADMIN_VENDOR_SOURCE_ROWS[
                    adminVendor.id
                ];

            const sourceVendor =
                vendorsBySourceRow.get(sourceRow);


            if (
                !sourceVendor ||
                !Array.isArray(adminVendor.editedFields)
            ) {
                return;
            }


            adminVendor.editedFields.forEach(
                function (field) {

                    const sourceField = fieldMap[field];


                    if (sourceField) {
                        sourceVendor[sourceField] =
                            adminVendor[field] || "";
                    }


                    if (field === "systemName") {
                        sourceVendor.displayName =
                            adminVendor.systemName || "";
                    }

                }
            );

        }
    );

}


applyAdminVendorOverrides();


