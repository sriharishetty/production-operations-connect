    /* ========================================================
       FAVORITES
       ======================================================== */

    function getFavorites() {

        try {

            return JSON.parse(
                localStorage.getItem(
                    "productionOpsVendorFavorites"
                )
            ) || [];

        } catch (error) {

            return [];

        }

    }


    function saveFavorites(
        favorites
    ) {

        localStorage.setItem(
            "productionOpsVendorFavorites",
            JSON.stringify(
                favorites
            )
        );

    }


    function updateFavoriteButton() {

        if (!currentVendor) {
            return;
        }


        const favorites =
            getFavorites();


        const key =
            String(
                currentVendor.sourceRow
            );


        const isFavorite =
            favorites.includes(key);


        vendorFavoriteButton.classList.toggle(
            "active",
            isFavorite
        );


        vendorFavoriteButton.textContent =
            isFavorite
                ? "★ Remove from Favorites"
                : "☆ Add to Favorites";

    }


    vendorFavoriteButton.addEventListener(
        "click",
        function () {

            if (!currentVendor) {
                return;
            }


            const favorites =
                getFavorites();


            const key =
                String(
                    currentVendor.sourceRow
                );


            const index =
                favorites.indexOf(key);


            if (index === -1) {

                favorites.push(key);

            } else {

                favorites.splice(
                    index,
                    1
                );

            }


            saveFavorites(
                favorites
            );


            updateFavoriteButton();

        }
    );


